"""SQLite for local development; PostgreSQL on Render via DATABASE_URL."""
import os, sqlite3
from pathlib import Path
PG = bool(os.environ.get('DATABASE_URL'))
if PG:
    import psycopg
    from psycopg.rows import dict_row

class Database:
    def __enter__(self):
        if PG:
            self.conn=psycopg.connect(os.environ['DATABASE_URL'],row_factory=dict_row,connect_timeout=12)
        else:
            self.conn=sqlite3.connect(os.environ.get('FAIRSPLIT_DB',str(Path(__file__).parent/'fairsplit.sqlite3')),timeout=25)
            self.conn.row_factory=sqlite3.Row
        return self
    def execute(self,sql,params=()):
        if PG:
            sql=sql.replace('?', '%s')
            # SQLite's case-insensitive comparison syntax is not supported in PostgreSQL.
            sql=sql.replace('alias=? COLLATE NOCASE','LOWER(alias)=LOWER(?)')
        return self.conn.execute(sql,params)
    def executemany(self,sql,rows):
        if PG:
            sql=sql.replace('?','%s')
            with self.conn.cursor() as cursor:
                cursor.executemany(sql,rows)
        else:self.conn.executemany(sql,rows)
    def __exit__(self,typ,value,tb):
        try:
            if typ:self.conn.rollback()
            else:self.conn.commit()
        finally:self.conn.close()

def connect():return Database()

def initialize():
    with connect() as c:
        if PG:
            c.execute('''CREATE TABLE IF NOT EXISTS sessions (id TEXT PRIMARY KEY,admin_hash TEXT NOT NULL,title TEXT NOT NULL,institution TEXT,created BIGINT NOT NULL,description TEXT,settings TEXT,closed INTEGER NOT NULL DEFAULT 0)''')
            c.execute('''CREATE TABLE IF NOT EXISTS questions (session TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,number INTEGER NOT NULL,question TEXT NOT NULL,PRIMARY KEY(session,number))''')
            c.execute('''CREATE TABLE IF NOT EXISTS assignments (session TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,token TEXT NOT NULL,alias TEXT NOT NULL,number INTEGER NOT NULL,gender TEXT,year TEXT,faculty TEXT,consent INTEGER NOT NULL,created BIGINT NOT NULL,research_token TEXT,age_band TEXT,programme TEXT,participant_note TEXT,PRIMARY KEY(session,token),UNIQUE(session,number),UNIQUE(session,alias))''')
            c.execute('''CREATE TABLE IF NOT EXISTS feedback (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,session TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,assignment_token TEXT NOT NULL,rating INTEGER NOT NULL,comment TEXT,created BIGINT NOT NULL,UNIQUE(session,assignment_token))''')
            c.execute('CREATE INDEX IF NOT EXISTS assignments_session_ix ON assignments(session)')
            c.execute('CREATE UNIQUE INDEX IF NOT EXISTS assignments_alias_casefold_ix ON assignments(session,LOWER(alias))')
            # All access is through the trusted Render backend, not the Supabase public Data API.
            for table in ('sessions','questions','assignments','feedback'):
                c.execute(f'ALTER TABLE public.{table} ENABLE ROW LEVEL SECURITY')
                c.execute(f'REVOKE ALL ON public.{table} FROM anon, authenticated')
        else:
            c.execute('CREATE TABLE IF NOT EXISTS sessions(id TEXT PRIMARY KEY, admin_hash TEXT NOT NULL,title TEXT NOT NULL,institution TEXT,created INTEGER NOT NULL)')
            c.execute('CREATE TABLE IF NOT EXISTS questions(session TEXT NOT NULL,number INTEGER NOT NULL,question TEXT NOT NULL,PRIMARY KEY(session,number))')
            c.execute('CREATE TABLE IF NOT EXISTS assignments(session TEXT NOT NULL,token TEXT NOT NULL,alias TEXT NOT NULL,number INTEGER NOT NULL,gender TEXT,year TEXT,faculty TEXT,consent INTEGER NOT NULL,created INTEGER NOT NULL,PRIMARY KEY(session,token), UNIQUE(session,number), UNIQUE(session,alias))')
            cols={r['name'] for r in c.execute('PRAGMA table_info(sessions)')}
            for field,kind in [('description','TEXT'),('settings','TEXT'),('closed','INTEGER NOT NULL DEFAULT 0')]:
                if field not in cols:c.execute(f'ALTER TABLE sessions ADD COLUMN {field} {kind}')
            cols={r['name'] for r in c.execute('PRAGMA table_info(assignments)')}
            for field,kind in [('research_token','TEXT'),('age_band','TEXT'),('programme','TEXT'),('participant_note','TEXT')]:
                if field not in cols:c.execute(f'ALTER TABLE assignments ADD COLUMN {field} {kind}')
            c.execute('CREATE TABLE IF NOT EXISTS feedback(id INTEGER PRIMARY KEY AUTOINCREMENT, session TEXT NOT NULL, assignment_token TEXT NOT NULL, rating INTEGER NOT NULL, comment TEXT,created INTEGER NOT NULL, UNIQUE(session,assignment_token))')
            c.execute('CREATE INDEX IF NOT EXISTS assignments_session_ix ON assignments(session)')
            c.execute('CREATE UNIQUE INDEX IF NOT EXISTS assignments_alias_casefold_ix ON assignments(session,alias COLLATE NOCASE)')
